// Pluralisation helper for piercing counts in RU UI:
//   1  → "1 прокол"
//   2,3,4 → "2 прокола"
//   5+, 0 → "5 проколов"
export function piercingCountLabel(n: number): string {
  const tail = n % 100;
  if (tail >= 11 && tail <= 14) return `${n} проколов`;
  const last = n % 10;
  if (last === 1) return `${n} прокол`;
  if (last >= 2 && last <= 4) return `${n} прокола`;
  return `${n} проколов`;
}

